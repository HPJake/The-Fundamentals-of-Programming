
#include <iostream>
using namespace std;

// f(m, n)：表示把 m 个相同的苹果放入 n 个相同的盘子中，
// 一共有多少种不同的放法。
// 允许盘子为空，且不考虑盘子的排列顺序。
int f(int m, int n) {

    // 递归终止条件
    // 情况1：m == 0，已经没有苹果需要分配
    //        剩下的盘子全部为空，只有 1 种放法。
    // 情况2：n == 1，只剩下一个盘子
    //        所有苹果只能放进这个盘子，也只有 1 种放法。
    if (m == 0 || n == 1) {
        return 1;
    }

    // 如果苹果数小于盘子数
    // 那么必然至少有一个盘子为空。
    // 因为盘子相同，去掉一个空盘不会影响方案数量。
    // 所以问题转化为：m 个苹果放入 n-1 个盘子。
    if (m < n) {
        return f(m, n - 1);
    }

    // 当 m >= n 时，将所有方案分为两类：

    // 第一类：所有盘子都不为空
    // 先给每个盘子放 1 个苹果，共使用 n 个。
    // 剩余 m-n 个苹果，可以继续分配到这 n 个盘子。
    // 对应 f(m-n, n)。

    // 第二类：至少有一个盘子为空
    // 因为盘子相同，可以去掉一个空盘。
    // 对应 f(m, n-1)。

    // 两类情况互不重复，并且包含所有可能的放法。
    // 所以总方案数等于两类方案数之和。
    return f(m - n, n) + f(m, n - 1);
}

int main() {
    int t;
    cin >> t;  // 输入测试数据的组数

    // 依次处理每一组测试数据
    for (int i = 0; i < t; i++) {
        int m, n;

        cin >> m >> n;  // m：苹果数，n：盘子数

        // 调用递归函数，计算不同放法的数量
        cout << f(m, n) << endl;
    }

    return 0;
}
